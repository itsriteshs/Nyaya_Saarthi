import {createRequire} from 'node:module';
import fs from 'node:fs';
const load=createRequire(import.meta.url);
const {chromium}=load(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1280,height:900}});
 const api='http://127.0.0.1:8002/api/v1';
 const supplied=process.env.RESEARCH_TEST_MATTER_ID;
 const created=supplied?null:await (await fetch(api+'/matters',{method:'POST',headers:{'content-type':'application/json'},body:JSON.stringify({originalText:'Research browser fixture only',language:'english'})})).json();
 const matterId=supplied||created.id;
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const output='backend/experiments/phase7/browser-check';fs.mkdirSync(output,{recursive:true});
 await page.route('**/api/v1/research/**',async route=>{
   const response=await route.fetch({url:route.request().url().replace('127.0.0.1:8000','127.0.0.1:8002')});
   await route.fulfill({response,headers:{...response.headers(),'access-control-allow-origin':'*'}});
 });
 await page.goto('http://127.0.0.1:3002/research');
 await page.getByRole('heading',{name:'Follow the evidence. Inspect the limits.'}).waitFor();
 if(!await page.getByRole('button',{name:'Inspect recorded trace'}).isDisabled())throw Error('No matter should disable inspect');
 await page.getByLabel('Matter ID',{exact:true}).fill('invalid');
 await page.getByRole('button',{name:'Inspect recorded trace'}).click();
 await page.getByRole('alert').filter({hasText:'Invalid matter ID'}).waitFor();
 await page.getByLabel('Matter ID',{exact:true}).fill(matterId);
 await page.getByRole('button',{name:'Inspect recorded trace'}).click();
 await page.getByRole('heading',{name:'Recorded decision trace',exact:true}).waitFor();
 await page.screenshot({path:output+'/trace-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Ablation studies',exact:true}).click();
 await page.getByRole('heading',{name:'Historical Phase 6 results — exploratory',exact:true}).waitFor();
 await page.getByLabel('Development artifact').selectOption('dev-20261023-v1');
 await page.getByRole('heading',{name:'Adversarial faithfulness screening by error type'}).waitFor();
 await page.screenshot({path:output+'/studies-desktop.png',fullPage:true});
 await page.setViewportSize({width:360,height:800});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile page overflow');
 await page.screenshot({path:output+'/studies-mobile.png',fullPage:true});
 await page.getByRole('button',{name:'Matter explainability',exact:true}).click();
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile trace overflow');
 await page.screenshot({path:output+'/trace-mobile.png',fullPage:true});
 await page.unroute('**/api/v1/research/**');
 await page.route('**/api/v1/research/catalog',route=>route.fulfill({json:{runs:[],historical:{},nli:{status:'unavailable'}},headers:{'access-control-allow-origin':'*'}}));
 await page.reload();await page.getByRole('button',{name:'Ablation studies',exact:true}).click();
 await page.getByRole('heading',{name:'No Phase 7 results yet'}).waitFor();
 await page.unroute('**/api/v1/research/catalog');
 await page.route('**/api/v1/research/catalog',route=>route.fulfill({status:503,json:{detail:'Research test unavailable'},headers:{'access-control-allow-origin':'*'}}));
 await page.reload();await page.getByRole('button',{name:'Ablation studies',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'Research artifacts unavailable'}).waitFor();
 if(errors.length)throw Error(errors.join('\n'));
 fs.writeFileSync(output+'/checks.json',JSON.stringify({passed:true,checks:['saved matter trace','invalid matter','historical artifacts','development selection','per-type table','360px studies no overflow','360px trace no overflow','empty artifacts','unavailable service','no page errors'],note:'Empty/error responses are test fixtures, not metrics.'},null,2));
 if(created)await fetch(api+'/matters/'+created.id,{method:'DELETE'});
 await browser.close();console.log('Research browser checks passed');
})().catch(e=>{console.error(e);process.exit(1)});
