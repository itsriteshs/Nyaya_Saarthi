"""Offline component-removal proxies; never changes production safety gates."""
import json
from collections import Counter
from app.config import BACKEND_DIR, DATASET_DIR
from app.services.nlp.ontology import ontology
from app.services import conversation

ROOT = BACKEND_DIR / "experiments"


def adaptive():
    cases = []
    with (DATASET_DIR / "adaptive_conversations.jsonl").open(encoding="utf-8") as stream:
        for line in stream:
            item = json.loads(line)
            if item.get("split") == "test": cases.append(item)
    total_required = initial_captured = final_captured = questions = redundant = first_agreement = first_compared = 0
    turns = []
    for item in cases:
        rows = ontology()["slots"].get(item["primary_intent_id"], [])
        required = {r["slot_name"] for r in rows if r["required_level"] == "required" and
                    json.loads(r.get("required_when_json") or "{}").get("when") == "intent_context"}
        first_user = next((t for t in item["turns"] if t.get("speaker") == "user"), {})
        initial = first_user.get("slot_updates", {})
        final = item.get("final_slot_state", {})
        total_required += len(required)
        initial_captured += len(required & initial.keys())
        final_captured += len(required & final.keys())
        system = [t for t in item["turns"] if t.get("speaker") == "system" and t.get("asks_for_slot")]
        questions += len(system)
        redundant += sum(t["asks_for_slot"] in initial for t in system)
        turns.append(len(system))
        facts = [{"id": f"initial:{key}", "key": key, "label": key, "value": str(value),
                  "normalizedValue": str(value), "resolutionStatus": "resolved", "confirmed": False}
                 for key, value in initial.items() if value]
        context = {"id": item["conversation_id"], "originalText": item["initial_query"],
                   "language": item["language"].lower(), "nlpAnalysis": {"intent": {"id": item["primary_intent_id"]}},
                   "facts": facts, "messages": [], "missingSlots": [], "answers": {}, "stage": "NEEDS_CLARIFICATION"}
        conversation.recompute(context)
        if system:
            first_compared += 1
            first_agreement += bool(context.get("currentQuestion") and context["currentQuestion"]["slot"] == system[0]["asks_for_slot"])
    return {"n": len(cases), "requiredSlotObservations": total_required,
            "withoutAdaptiveCapturedRate": initial_captured / total_required if total_required else None,
            "recordedFinalCapturedRate": final_captured / total_required if total_required else None,
            "absoluteChange": (final_captured - initial_captured) / total_required if total_required else None,
            "recordedQuestionCount": questions, "recordedRedundantQuestionRate": redundant / questions if questions else None,
            "meanRecordedTurns": sum(turns) / len(turns) if turns else None,
            "policyFirstQuestionAgreement": first_agreement / first_compared if first_compared else None,
            "firstQuestionCompared": first_compared,
            "caveat": "Initial and final coverage use only recorded slot updates. The final recorded conversation is not generated by the current application, so this is a dataset-level ablation proxy."}


def rules():
    frozen = json.loads((ROOT / "manifests" / "phase6_evidence_packages.json").read_text())
    rows = []
    for item in frozen["cases"]:
        evidence = item["package"]["evidence"]
        matched = {r["provisionId"] for r in item["package"]["ruleEvaluations"] if r["status"] == "MATCHED"}
        unsupported = [e["provisionId"] for e in evidence if e["provisionId"] not in matched]
        rows.append({"caseId": item["caseId"], "retrieved": len(evidence), "matchedRuleProvisions": len(matched),
                     "retrievedWithoutMatchedRule": unsupported})
    return {"n": len(rows), "cases": rows,
            "withoutRulesUnsupportedApplicabilityExposure": sum(bool(r["retrievedWithoutMatchedRule"]) for r in rows) / len(rows) if rows else None,
            "caveat": "Counts a retrieved provision lacking a MATCHED structured rule. It does not score a generated legal conclusion or assert that retrieval-only would actually make one."}


def run():
    retrieval = json.loads((ROOT / "metrics" / "phase6_retrieval.json").read_text())
    models = {}
    for model_id in ("llama3.2-3b", "mistral-7b"):
        path = ROOT / "metrics" / f"phase6_llm_{model_id}.json"
        models[model_id] = json.loads(path.read_text())["overall"] if path.exists() else None
    result = {"adaptiveQuestioning": adaptive(), "ruleMatching": rules(),
              "retrieval": {name: retrieval["variants"][name] for name in ("bm25", "semantic", "hybrid")},
              "llmVersusDeterministic": {"deterministicAvailable": True, "llm": models,
                  "humanUsefulnessDifference": None,
                  "reason": "No blinded human quality ratings are available."},
              "interpretation": "These are separate component proxies with different case sets; there is no defensible single full-system score."}
    path = ROOT / "metrics" / "phase6_ablations.json"
    path.write_text(json.dumps(result, indent=2), encoding="utf-8")
    return result


if __name__ == "__main__":
    print(json.dumps(run(), indent=2))
